/**
 * Build the committed sample report from the demo corpus.
 *
 * Runs a mock trip (no model call, no API cost) over
 * `examples/tiny-memory-library` and writes the resulting report to
 * `docs/sample-report.md`, so people can see the output shape before pointing
 * Reverie at their own vault.
 *
 * Usage: node examples/build-sample-report.mjs
 */

import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { writeRun } from "../lib/artifacts.js";
import { DEFAULTS } from "../lib/config.js";
import { loadCorpus } from "../lib/corpus.js";
import { runMock } from "../lib/mock.js";
import { buildIndex } from "../lib/search.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const corpusRoot = path.join(here, "tiny-memory-library");
const output = path.join(here, "..", "docs", "sample-report.md");

const home = await mkdtemp(path.join(tmpdir(), "reverie-sample-"));
const previousHome = process.env.DSH_HOME;
process.env.DSH_HOME = home;
try {
  const settings = {
    ...DEFAULTS,
    minDocumentChars: 24,
    maxDocuments: 400,
    language: "zh",
    sources: [{ id: "demo", kind: "folder", root: corpusRoot, extensions: ["md"] }],
  };
  const startedAt = Date.now();
  const corpus = await loadCorpus(settings, { cwd: here, refresh: true });
  const index = buildIndex(corpus.documents);
  const mock = runMock({ index, documents: corpus.documents, language: "zh", maxNoteChars: 2_000 });
  const endedAt = Date.now();
  const sources = corpus.sources.map((source) => ({ id: source.id, kind: source.kind, documents: source.documents }));
  const chars = corpus.documents.reduce((sum, document) => sum + document.text.length, 0);
  const written = await writeRun({
    root: path.join(home, "reverie", "runs"),
    meta: {
      run_id: "rev-20260307-030000-demo",
      day: "2026-03-07",
      mode: "mock",
      provider: "",
      model: "",
      started_at: new Date(startedAt).toISOString(),
      ended_at: new Date(endedAt).toISOString(),
      stop_reason: mock.stopReason,
      language: "zh",
      corpus: { documents: corpus.documents.length, chars, sources, problems: corpus.problems },
      touched: (mock.seeds ?? []).map((seed) => ({ locator: seed.locator, time: seed.time })),
      budget: { max_steps: 8, max_input_tokens: 60_000, max_output_tokens: 2_048, timeout_ms: 600_000 },
      usage: mock.usage,
    },
    note: mock.note,
    evidence: (mock.seeds ?? []).map((seed) => ({
      locator: seed.locator,
      time: seed.time === null ? "" : new Date(seed.time).toISOString(),
      snippet: seed.snippet,
    })),
    events: mock.events,
    language: "zh",
  });

  const report = await readFile(path.join(written.directory, "report.md"), "utf8");
  const banner = [
    "<!-- Generated by `node examples/build-sample-report.mjs`; a mock run, no model call. -->",
    "",
    "> 这是对 `examples/tiny-memory-library/` 这份**虚构** demo 语料跑出的样例报告（mock，不调用模型）。",
    "> 想看真实形状：把 `reverie_config` 的 `sources` 指向你自己的笔记目录，跑一次 mock 即可。",
    "",
    "",
  ].join("\n");
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, `${banner}${report}`, "utf8");
  console.log(`wrote ${output}`);
  console.log(`corpus: ${corpus.documents.length} documents from ${sources.length} source(s)`);
  console.log(`note: ${mock.note.length} chars, stop reason ${mock.stopReason}`);
} finally {
  if (previousHome === undefined) delete process.env.DSH_HOME;
  else process.env.DSH_HOME = previousHome;
  await rm(home, { recursive: true, force: true });
}
